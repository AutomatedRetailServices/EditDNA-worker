def media_dir(tmp_path_factory):
    return tmp_path_factory.mktemp("post_render_media_qc")


@pytest.fixture(scope="module")
def clean_av(media_dir):
    path = str(media_dir / "clean_av.mp4")
    _ffmpeg([
        "-f", "lavfi", "-i", "sine=frequency=440:duration=2",
        "-f", "lavfi", "-i", "testsrc=size=64x64:rate=25:duration=2",
        "-c:v", "libx264", "-c:a", "aac", "-shortest", "-y", path,
    ])
    return path


