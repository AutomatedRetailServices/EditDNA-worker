def test_bounded_physical_repair_loop_passes_when_a_later_attempt_is_clean(clean_av, corrupt_media):
    calls = []

    def render_attempt(attempt_index):
        calls.append(attempt_index)
        return corrupt_media if attempt_index == 0 else clean_av

    result = run_bounded_physical_repair_loop(render_attempt, max_attempts=3)

    assert isinstance(result, BoundedPhysicalRepairResult)
    assert result.status == "PASS"
    assert len(result.attempts) == 2
    assert result.attempts[0].repaired is False
    assert result.attempts[1].repaired is True
    assert calls == [0, 1]


def test_bounded_physical_repair_loop_terminates_as_needs_human_review(corrupt_media):
    result = run_bounded_physical_repair_loop(lambda attempt_index: corrupt_media, max_attempts=3)

    assert result.status == "NEEDS_HUMAN_REVIEW"
    assert len(result.attempts) == 3  # bounded -- never spins past max_attempts
    assert all(a.repaired is False for a in result.attempts)


def test_bounded_physical_repair_loop_never_claims_pass_while_a_finding_remains(corrupt_media):
    result = run_bounded_physical_repair_loop(lambda attempt_index: corrupt_media, max_attempts=2)
    assert result.status != "PASS"


def test_bounded_physical_repair_loop_refuses_a_non_physical_finding_kind(clean_av):
    from cutsell_worker.post_render_watch_listen_qc import PostRenderFinding, PostRenderQCResult

    def fake_semantic_qc(_media_path):
        return PostRenderQCResult(
            status="FAIL",
            findings=(PostRenderFinding(
                kind="DUPLICATE_IDEA", start=0.0, end=0.0, detail={}, routes_to="BestTakeResolver",
            ),),
        )

    with pytest.raises(ValueError):
        run_bounded_physical_repair_loop(lambda attempt_index: clean_av, qc_check=fake_semantic_qc)
